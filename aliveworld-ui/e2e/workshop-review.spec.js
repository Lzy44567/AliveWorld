import { test, expect } from '@playwright/test';

test('工坊部分审阅保留未选方案并可重新载入', async ({ page, request }) => {
  await page.goto('/');
  await page.waitForTimeout(500);
  const later = page.getByRole('button', { name: '稍后再说' });
  if (await later.isVisible()) await later.click();
  await page.getByTestId('tab-world').click();
  await page.getByRole('button', { name: '🌐 全局图鉴' }).click();
  await page.getByTestId('asset-new').click();
  const editor = page.getByTestId('asset-editor');
  await editor.getByTestId('asset-name').fill('工坊审阅专用世界');
  await editor.getByText('世界概述', { exact: true }).locator('..').getByRole('textbox').fill('浮岛上的轻松小店');
  await editor.getByTestId('asset-editor-save').click();
  await expect(editor).toBeHidden();
  await page.getByRole('button', { name: '🧰 工坊' }).click();
  await page.locator('[data-workshop-asset-name="工坊审阅专用世界"]').click();
  await page.locator('textarea[placeholder*="Ctrl+Enter"]').fill('AW_REVIEW_BATCH 请给出三个条目草案');
  await page.getByRole('button', { name: '发送', exact: true }).click();
  const review = page.getByTestId('workshop-review-proposed');
  await expect(review.locator('article')).toHaveCount(3);
  const brief = page.getByTestId('workshop-creative-brief');
  await brief.locator('summary').click();
  await expect(brief.locator('textarea')).toHaveValue('轻松探索浮岛，不写战争');
  await brief.locator('textarea').fill('  轻松探索浮岛，侧重交朋友，不写战争  ');
  await brief.getByRole('button', { name: '保存目标' }).click();
  await expect(brief.getByRole('button', { name: '保存目标' })).toBeDisabled();
  await review.getByRole('checkbox', { name: '选择浮岛', exact: true }).check();
  await review.getByRole('button', { name: '接受所选', exact: true }).click();
  await expect(review.locator('article')).toHaveCount(2);
  await review.getByRole('checkbox', { name: '选择商人', exact: true }).check();
  await page.screenshot({ path: '../build/workshop-review-desktop.png', fullPage: true });
  await review.getByRole('button', { name: '拒绝所选', exact: true }).click();
  await expect(review.locator('article')).toHaveCount(1);
  await page.reload();
  await page.waitForTimeout(500);
  if (await later.isVisible()) await later.click();
  await page.getByRole('button', { name: '🧰 工坊' }).click();
  await page.locator('[data-workshop-asset-name="工坊审阅专用世界"]').click();
  await expect(review.locator('article')).toHaveCount(1);
  await expect(review).toContainText('小店');
  await brief.locator('summary').click();
  await expect(brief.locator('textarea')).toHaveValue('轻松探索浮岛，侧重交朋友，不写战争');
  await review.getByRole('button', { name: '接受全部', exact: true }).click();
  await expect(review).toHaveCount(0);
  await page.getByTestId('workshop-publish').click();
  await expect(page.getByTestId('workshop-new-round')).toBeVisible();
  const book = await (await request.get('/api/v1/lobby/assets/worldbooks/工坊审阅专用世界')).json();
  expect(book.parsed.entries.map(item => item.name)).toEqual(expect.arrayContaining(['浮岛', '小店']));
  expect(book.parsed.entries.map(item => item.name)).not.toContain('商人');
  expect(JSON.stringify(book.parsed)).not.toContain('侧重交朋友');
  await page.getByTestId('workshop-new-round').click();
  await expect(brief.locator('textarea')).toHaveValue('轻松探索浮岛，侧重交朋友，不写战争');
});
