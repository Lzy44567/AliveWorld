import { test, expect } from '@playwright/test';

test('工坊部分审阅保留未选方案并可重新载入', async ({ page, request }) => {
  await page.goto('/');
  await page.waitForTimeout(500);
  const later = page.getByRole('button', { name: '稍后再说' });
  if (await later.isVisible()) await later.click();
  await page.getByTestId('tab-world').click();
  await page.getByRole('button', { name: '🌐 全局图鉴' }).click();
  await page.getByTestId('asset-new').click();
  const editor = page.getByTestId('asset-editor');
  await editor.getByTestId('asset-name').fill('工坊审阅专用世界');
  await editor.getByText('世界概述', { exact: true }).locator('..').getByRole('textbox').fill('浮岛上的轻松小店');
  await editor.getByTestId('asset-editor-save').click();
  await expect(editor).toBeHidden();
  await page.getByRole('button', { name: '🧰 工坊' }).click();
  await page.locator('[data-workshop-asset-name="工坊审阅专用世界"]').click();
  await page.locator('textarea[placeholder*="Ctrl+Enter"]').fill('AW_REVIEW_BATCH 请给出三个条目草案');
  await page.getByRole('button', { name: '发送', exact: true }).click();
  const review = page.getByTestId('workshop-review-proposed');
  await expect(review.locator('article')).toHaveCount(3);
  const conversation = page.getByTestId('workshop-conversation');
  const beforeFocus = await conversation.boundingBox();
  const input = page.locator('textarea[placeholder*="Ctrl+Enter"]');
  await input.fill('专注模式保留的草稿');
  await page.getByTestId('workshop-focus-toggle').click();
  await expect(page.locator('[data-workshop-asset-name="工坊审阅专用世界"]')).toBeHidden();
  const afterFocus = await conversation.boundingBox();
  expect(afterFocus.width).toBeGreaterThan(beforeFocus.width);
  expect(afterFocus.height).toBeGreaterThan(beforeFocus.height);
  await expect(input).toHaveValue('专注模式保留的草稿');
  const lastArticle = await review.locator('article').last().boundingBox();
  const actions = await review.getByTestId('workshop-review-actions').boundingBox();
  expect(actions.y).toBeGreaterThanOrEqual(lastArticle.y + lastArticle.height);
  await page.screenshot({ path: '../build/workshop-focus-desktop.png', fullPage: true });
  await page.setViewportSize({ width: 900, height: 700 });
  await expect(page.getByTestId('workshop-focus-toggle')).toBeInViewport();
  await expect(input).toBeInViewport();
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(900);
  await page.screenshot({ path: '../build/workshop-focus-narrow.png', fullPage: true });
  await page.setViewportSize({ width: 1600, height: 1000 });
  await page.keyboard.press('Escape');
  await expect(page.locator('[data-workshop-asset-name="工坊审阅专用世界"]')).toBeVisible();
  await expect(input).toHaveValue('专注模式保留的草稿');
  const brief = page.getByTestId('workshop-creative-brief');
  await brief.locator('summary').click();
  await expect(brief.locator('textarea')).toHaveValue('轻松探索浮岛，不写战争');
  await brief.locator('textarea').fill('  轻松探索浮岛，侧重交朋友，不写战争  ');
  await brief.getByRole('button', { name: '保存目标' }).click();
  await expect(brief.getByRole('button', { name: '保存目标' })).toBeDisabled();
  await review.getByRole('checkbox', { name: '选择浮岛', exact: true }).check();
  await review.getByRole('button', { name: '接受所选', exact: true }).click();
  await expect(review.locator('article')).toHaveCount(2);
  await review.getByRole('checkbox', { name: '选择商人', exact: true }).check();
  await page.screenshot({ path: '../build/workshop-review-desktop.png', fullPage: true });
  await review.getByRole('button', { name: '拒绝所选', exact: true }).click();
  await expect(review.locator('article')).toHaveCount(1);
  await page.reload();
  await page.waitForTimeout(500);
  if (await later.isVisible()) await later.click();
  await page.getByRole('button', { name: '🧰 工坊' }).click();
  await page.locator('[data-workshop-asset-name="工坊审阅专用世界"]').click();
  await expect(review.locator('article')).toHaveCount(1);
  await expect(review).toContainText('小店');
  await brief.locator('summary').click();
  await expect(brief.locator('textarea')).toHaveValue('轻松探索浮岛，侧重交朋友，不写战争');
  await review.getByRole('button', { name: '接受全部', exact: true }).click();
  await expect(review).toHaveCount(0);
  await page.getByTestId('workshop-publish').click();
  await expect(page.getByTestId('workshop-new-round')).toBeVisible();
  const book = await (await request.get('/api/v1/lobby/assets/worldbooks/工坊审阅专用世界')).json();
  expect(book.parsed.entries.map(item => item.name)).toEqual(expect.arrayContaining(['浮岛', '小店']));
  expect(book.parsed.entries.map(item => item.name)).not.toContain('商人');
  expect(JSON.stringify(book.parsed)).not.toContain('侧重交朋友');
  // Send directly from the published checkpoint; a new safe draft is opened.
  let releaseStart;
  const startGate = new Promise(resolve => { releaseStart = resolve; });
  await page.route('**/api/v1/worldbooks/workshops/start', async route => {
    await startGate;
    await route.continue();
  });
  await input.fill('AW_CONTINUITY_PROBE');
  await page.getByRole('button', { name: '发送', exact: true }).click();
  await expect(input).toHaveValue('');
  await input.fill('下一条尚未发送的新草稿');
  releaseStart();
  await expect(conversation).toContainText('历史取材就绪');
  await expect(input).toHaveValue('下一条尚未发送的新草稿');
  await page.unroute('**/api/v1/worldbooks/workshops/start');
  await expect(page.getByTestId('workshop-history')).toContainText('AW_REVIEW_BATCH');
  const memorySettings = page.getByTestId('workshop-context-settings');
  await memorySettings.locator('summary').click();
  await expect(page.getByTestId('workshop-context-info')).toContainText('历史节选 2 条');
  await memorySettings.getByRole('checkbox').uncheck();
  await input.fill('AW_CONTINUITY_PROBE');
  await page.getByRole('button', { name: '发送', exact: true }).click();
  await expect(conversation).toContainText('未携带旧讨论');
  await expect(brief.locator('textarea')).toHaveValue('轻松探索浮岛，侧重交朋友，不写战争');
  await page.reload();
  await later.click();
  await page.getByRole('button', { name: '🧰 工坊' }).click();
  await page.locator('[data-workshop-asset-name="工坊审阅专用世界"]').click();
  await expect(conversation).toContainText('历史取材就绪');
  await brief.locator('summary').click();
  await expect(brief.locator('textarea')).toHaveValue('轻松探索浮岛，侧重交朋友，不写战争');
  await page.getByTestId('workshop-publish').click();
  await expect(page.getByTestId('workshop-new-round')).toBeVisible();
  await input.fill('AW_CONTINUITY_PROBE');
  await page.getByRole('button', { name: '发送', exact: true }).click();
  await expect(page.getByTestId('workshop-history').locator('details')).toHaveCount(2);
  await expect(conversation).toContainText('历史取材就绪');
});
