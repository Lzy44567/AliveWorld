import { test, expect } from '@playwright/test';

test('后台修订轻提示、隐藏详情、原书审阅和撤回记录', async ({ page, request }) => {
  await request.delete('http://127.0.0.1:18765/__test__/requests');
  await page.addInitScript(() => localStorage.setItem('aw_onboarding_v1', JSON.stringify({ completed: true })));
  await page.goto('/');
  await page.getByTestId('tab-saves').click();
  await page.getByRole('button', { name: '+ 新局' }).click();
  await page.getByTestId('new-game-name').fill('修订记录验收');
  const created = page.waitForResponse(r => r.url().endsWith('/game/start') && r.request().method() === 'POST');
  const baseline = page.waitForResponse(r => r.url().includes('/worldbook-activity'));
  await page.getByTestId('new-game-submit').click();
  const { session_id } = await (await created).json();
  await baseline;
  await expect(page.getByTestId('worldbook-activity-notice')).toHaveCount(0);
  const base = `/api/v1/game/${session_id}`;
  await request.post(`${base}/story_config`, { data: { world_premise: '', plot_compass: '', story_settings: { worldbookCaptureReview: true, entitiesEnabled: false } } });
  await page.getByTestId('story-action-input').fill('【AW_BOOK:manual】法令');
  await page.getByTestId('story-action-submit').click();
  const notice = page.getByTestId('worldbook-activity-notice');
  await expect(notice).toContainText('2 条修订记录', { timeout: 20_000 });
  expect(await notice.textContent()).not.toContain('候选1');
  await notice.click();
  const panel = page.getByRole('region', { name: '世界书修订记录', exact: true });
  await expect(panel.getByTestId('worldbook-activity-row')).toHaveCount(2);
  await expect(panel).toContainText('2 条待审');
  await expect(panel.getByText('候选1', { exact: true })).toHaveCount(0);
  const plain = await (await request.get(`${base}/worldbook-activity`)).json();
  expect(JSON.stringify(plain)).not.toContain('候选法令');
  await panel.getByRole('checkbox', { name: '显示条目详情（可能包含隐藏设定）' }).check();
  await panel.getByText('候选1', { exact: true }).click();
  await expect(panel).toContainText('候选法令1');
  await page.screenshot({ path: '../build/worldbook47-history.png' });
  // Search filtering must not prevent opening the exact original book.
  await page.getByPlaceholder('搜索名称或标签...').fill('不存在的过滤词');
  await panel.getByRole('button', { name: '打开原书审阅' }).first().click();
  const editor = page.getByTestId('asset-editor');
  await expect(editor.getByTestId('worldbook-review-toolbar')).toContainText('待审 2 项');
  await editor.getByRole('button', { name: '全部拒绝', exact: true }).click();
  await expect(editor.getByTestId('worldbook-review-toolbar')).toHaveCount(0);
  await editor.getByRole('button', { name: '取消', exact: true }).click();
  await panel.getByRole('button', { name: '刷新记录' }).click();
  await expect(panel).toContainText('0 条待审');
  await expect(panel.getByText('已拒绝', { exact: true })).toHaveCount(2);
  await page.getByTestId('story-undo').click();
  await expect(page.getByTestId('story-action-submit')).toBeEnabled();
  await panel.getByRole('button', { name: '刷新记录' }).click();
  await expect(panel.getByText('源回合已撤回', { exact: true })).toHaveCount(4);
  const calls = (await (await request.get('http://127.0.0.1:18765/__test__/requests')).json()).requests;
  expect(calls.filter(c => c.kind === 'worldbook_capture')).toHaveLength(1);
});
