import { test, expect } from '@playwright/test';

test('实体计划、行动、改名、死亡与撤回保留一致账本', async ({ page, request }) => {
  await page.goto('/');
  await page.waitForTimeout(500);
  const later = page.getByRole('button', { name: '稍后再说' });
  if (await later.isVisible()) await later.click();
  await page.getByTestId('tab-saves').click();
  await page.getByRole('button', { name: '+ 新局' }).click();
  await page.getByTestId('new-game-name').fill('实体账本合成验收');
  await page.getByTestId('new-game-premise').fill('玩家在旅馆；商会在远方运输药材。');
  const created = page.waitForResponse(r => r.url().endsWith('/game/start') && r.request().method() === 'POST');
  await page.getByTestId('new-game-submit').click();
  let id = (await (await created).json()).session_id;
  const put = await request.post(`/api/v1/game/${id}/assets/entities/验收商会`, { data: { parsed_data: { name: '验收商会', motive: '完成运输', is_active: true } } });
  expect(put.ok()).toBeTruthy();
  async function send(tag) {
    await page.getByTestId('story-action-input').fill(`【AW_ENTITY:${tag}】等待`);
    await page.getByTestId('story-action-submit').click();
    await expect(page.getByTestId('story-action-submit')).toBeEnabled();
  }
  const ledger = async () => (await (await request.get(`/api/v1/game/${id}/causal-ledger`)).json());
  const assets = async () => (await (await request.get(`/api/v1/game/${id}/local_assets`)).json()).entities;
  await send('plan');
  expect((await ledger()).influences).toHaveLength(0);
  expect((await ledger()).events[0].kind).toBe('plan');
  await send('action');
  const identity = (await assets())[0].id;
  expect((await ledger()).influences[0].source_links[0].entity_id).toBe(identity);
  const renamed = await request.post(`/api/v1/game/${id}/assets/entities/验收商会/rename`, { data: { new_name: '新商会' } });
  expect(renamed.ok()).toBeTruthy();
  await send('dead');
  expect((await assets())[0]).toMatchObject({ id: identity, lifecycle: 'dead', is_active: false });
  expect((await ledger()).influences[0]).toMatchObject({ status: 'active', source_links: [{ entity: '新商会', entity_id: identity, source_dead: true }] });
  await page.getByTestId('tab-entity').click();
  await page.getByRole('button', { name: '🛡️ 本局专属' }).click();
  await page.getByRole('button', { name: '因果账本', exact: true }).click();
  await page.getByTestId('entity-event-history').locator('summary').first().click();
  await expect(page.getByTestId('entity-event-row')).toHaveCount(3);
  await expect(page.getByTestId('entity-event-history')).toContainText('计划 · 尚未执行');
  await page.getByText('依据与知情范围', { exact: true }).nth(1).click();
  await expect(page.getByTestId('entity-event-history')).toContainText('商会收到订单并拥有一辆车');
  await page.screenshot({ path: '../build/entity-ledger-desktop.png', fullPage: true });
  expect((await request.post(`/api/v1/game/${id}/undo`)).ok()).toBeTruthy();
  expect((await assets())[0]).toMatchObject({ id: identity, lifecycle: 'alive' });
  expect((await ledger()).events).toHaveLength(2);
  const reroll = await request.post(`/api/v1/game/${id}/reroll`, { data: { entities_enabled: true } });
  expect(reroll.ok()).toBeTruthy();
  expect((await ledger()).events).toHaveLength(2);
  expect((await ledger()).influences).toHaveLength(1);
  await page.reload();
  await page.getByTestId('tab-saves').click();
  const loaded = page.waitForResponse(r => r.url().endsWith('/game/load') && r.request().method() === 'POST');
  await page.locator('[data-save-name="实体账本合成验收"]').getByTestId('save-load').click();
  id = (await (await loaded).json()).session_id;
  expect((await assets())[0].id).toBe(identity);
  expect((await ledger()).events).toHaveLength(2);
  expect((await ledger()).influences[0].source_links[0].entity_id).toBe(identity);
});
