"""Prompt contract for causal continuity across story turns."""

CONTINUITY_RULES = """【剧情连续性与信息通道】
1. 先区分客观事实、角色观察和角色认知。“某处没找到”只证明该次搜索未发现，不能自动推出别处也没有、从未存在或玩家在撒谎。
2. 新的外部介入必须有当前上下文中已经存在的因果通道，例如目击者已离开、警报在屏蔽前发出、固定线路仍可用。若无法指出通道，不得凭空加入保安、警察、路人、电话、对讲机或巧合故障来强行制造阻力。
3. 已确认的物理限制持续有效，直到正文给出可追溯的新原因。信号被完全屏蔽后，无线电话、移动网络和对讲机不能工作；不得只为绕过玩家行动临时编造过热、自动解除或未知后门。
4. NPC 可以凭自身意志反抗、隐瞒或利用现场已有条件，但不能获得上下文没有建立的信息、工具或支援。
5. 若旧正文与玩家本回合明确纠错冲突，且旧描述没有世界书绝对规则或玩家输入支持，以纠错后的事实继续；不要在后续回合换一种措辞重复同一错误。
6. 法律、道德或“现实中通常如此”只能影响已有参与者的判断，不能替代报警、目击、通信等因果通道。不得为了惩罚违法或冒犯行为，让所有未来候选都换着方式强制导向警察、保安、投降或被捕。
7. 若候选或正文引入警察、保安、军队、邻居、媒体等新的外部力量，必须能从当前上下文逐项回答“谁在何时通过什么可用通道把什么信息传了出去”。答不出来就视为因果条件不成立，不得用“系统自动报警、有关部门注意到、监控恰好联网、保安直觉察觉”等新设定补洞。
8. 外部力量不是默认反派，也不是维护现实感的必需品。当前故事没有已经入场或获得信息的执法/安保力量时，不得让多数候选换着措辞汇聚到盘查、包围、投降、认罪或被捕；必须保留基于现场既有参与者和条件继续发展的有效路径。
9. `npc_states` 只描述本回合仍在当前场景或正在直接作用于场景的对象。已离开、未出现、只存在于回忆中的人物不要重复写入；离场对象写入 `status_deletions`。"""


def continuity_instruction() -> str:
    return CONTINUITY_RULES
