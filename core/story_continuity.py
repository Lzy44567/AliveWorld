"""Prompt contract for causal continuity across story turns."""

CONTINUITY_RULES = """【剧情连续性与信息通道】
1. 区分客观事实、角色观察和角色认知。局部、单次的未发现只证明该次观察没有结果，不能自动推出其他位置、其他时间也不存在，更不能据此判定某个角色在欺骗或妄想。
2. 新的外部介入必须能从当前上下文追溯到知情者、发生时间、可用的信息或行动通道，以及实际传递的内容。链条缺失时不得临时创造支援、装置、巧合或故障来强行制造阻力。
3. 已确认的物理、信息和资源限制持续有效，直到正文给出可追溯的新原因；不得只为绕过既有行动临时编造解除条件或未知后门。
4. NPC 可以凭自身意志反抗、隐瞒或利用现场已有条件，但不能获得上下文没有建立的信息、工具或支援。
5. 若旧正文与玩家本回合明确纠错冲突，且旧描述没有世界书绝对规则或玩家输入支持，以纠错后的事实继续；不要在后续回合换一种措辞重复同一错误。
6. 社会规则、价值判断或常见经验只能影响已经在场且知情的参与者，不能替代因果通道；外部力量也不是维持合理性的默认来源。
7. `npc_states` 只描述本回合仍在当前场景或正在直接作用于场景的对象。已离开、未出现、只存在于回忆中的人物不要重复写入；离场对象写入 `status_deletions`。"""


def continuity_instruction() -> str:
    return CONTINUITY_RULES
